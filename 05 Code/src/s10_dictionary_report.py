"""Step 10 - data dictionary + data quality report, generated from the actual outputs."""
from __future__ import annotations

import itertools

import numpy as np
import pandas as pd

from common import ENSO_INDICES, GEOGRAPHIES, INTERIM, REPORTS, active, geo_dir, variant_dir, write_csv
from feature_registry import REG

DICT_COLS = ["feature", "description", "source", "source_file", "year", "geographic_level", "numerator", "denominator",
             "formula", "unit", "missing_value_rule", "notes", "group", "role", "table"]


def md_table(df: pd.DataFrame, floatfmt: int = 2) -> str:
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda x: "" if pd.isna(x) else f"{x:.{floatfmt}f}")
    head = "| " + " | ".join(map(str, df.columns)) + " |\n|" + "---|" * len(df.columns) + "\n"
    return head + "\n".join("| " + " | ".join(map(str, r)) + " |" for r in df.astype(str).values) + "\n"


def run(cfg: dict) -> None:
    reg = pd.DataFrame(REG)[DICT_COLS]
    write_csv(reg, INTERIM / "data_dictionary.csv")

    geo, idx = active(cfg, "district_geography"), active(cfg, "enso_index")
    m = pd.read_csv(INTERIM / "maharashtra_district_feature_table.csv")
    master_reg = reg[reg.table == "maharashtra_district_feature_table.csv"].set_index("feature")
    scope = m[m.in_index_scope]
    cand = [f for f in master_reg.index if master_reg.loc[f, "role"] == "pca_candidate"]
    ctx = [f for f in master_reg.index if master_reg.loc[f, "role"] == "context"]
    ids = [f for f in master_reg.index if master_reg.loc[f, "role"] == "identifier"]

    # missingness
    miss = pd.DataFrame({"feature": m.columns, "n_missing_all": m.isna().sum().values,
                         "n_missing_in_scope": scope.isna().sum().reindex(m.columns).values})
    miss["districts_missing"] = [", ".join(m.loc[m[c].isna(), "census_2011_district_name"].astype(str)) for c in m.columns]
    miss = miss[miss.n_missing_all > 0]

    # redundancy: |r| >= 0.9 among candidate variables within scope
    num = scope[cand].astype(float)
    corr = num.corr()
    red = [(a, b, corr.loc[a, b]) for a, b in itertools.combinations(cand, 2) if abs(corr.loc[a, b]) >= 0.9]
    red = pd.DataFrame(red, columns=["feature_1", "feature_2", "pearson_r"]).sort_values("pearson_r", key=abs, ascending=False)

    # variant comparison (same district set: geography A)
    a_r = pd.read_csv(variant_dir("A", "RONI") / "maharashtra_district_feature_table.csv").set_index("district_id")
    a_o = pd.read_csv(variant_dir("A", "ONI_v6") / "maharashtra_district_feature_table.csv").set_index("district_id")
    clim_cols = [c for c in a_r.columns if c.startswith(("rain_en", "enso_rain", "rain_nonen"))]
    vc = pd.DataFrame({"feature": clim_cols,
                       "corr_RONI_vs_ONI_v6_across_districts": [a_r[c].corr(a_o[c]) for c in clim_cols],
                       "mean_RONI": [a_r[c].mean() for c in clim_cols], "mean_ONI_v6": [a_o[c].mean() for c in clim_cols]})
    enso_cmp = pd.read_csv(INTERIM / "enso_index_comparison.csv")
    enso_cmp = enso_cmp[enso_cmp.in_study_period]

    # QA inputs
    rq = pd.read_csv(INTERIM / "rainfall_qa.csv")
    gq = pd.read_csv(INTERIM / "variants" / "rainfall_grid_qa_by_year.csv")
    vq = pd.read_csv(INTERIM / "village_directory_qa.csv")
    aq = pd.read_csv(INTERIM / "agriculture_census_qa.csv")
    icr = pd.read_csv(geo_dir("A") / "village_directory_vs_icrisat_net_area.csv")
    chk = pd.read_csv(INTERIM / "enso_cpc_table_check.csv")
    val = pd.read_csv(INTERIM / "drought_validation.csv")
    cw = pd.read_csv(INTERIM / "district_crosswalk.csv")
    cq = pd.read_csv(INTERIM / "variants" / "validation_gr2023_revenue_circles_qa.csv")
    names = cw[cw.geography_version == geo].set_index("district_id").census_2011_district_name
    def _default(v: dict) -> str:
        if "active" in v:
            return str(v["active"])
        if "departure_pct" in v:
            return f"{v['departure_pct']}% ({v.get('comparison', '')})"
        return ""
    unresolved = [(k, _default(v), ", ".join(map(str, v.get("options", {}).keys())) if isinstance(v.get("options"), dict) else "value in config")
                  for k, v in cfg["decisions"].items() if v.get("status") == "UNRESOLVED"]

    L = []
    w = L.append
    w("# Data Quality Report - Maharashtra district feature table\n")
    w("_Generated by `src/s10_dictionary_report.py` from the pipeline outputs. Do not edit by hand; re-run `python src/run_pipeline.py`._\n")
    w(f"**Active variant:** geography **{geo}**, ENSO index **{idx}** (see `config/project_decisions.yaml`). "
      "All four variants (geography A/B x RONI/ONI v6) are in `data/interim/variants/`.\n")
    w("No PCA, standardisation, clustering, variable removal or vulnerability scoring has been performed.\n")

    w("## 1. How many districts are in the final geography, and why?\n")
    for g in GEOGRAPHIES:
        c = cw[cw.geography_version == g]
        w(f"- Geography **{g}**: {len(c)} districts; {int(c.in_index_scope_default.sum())} in the default index scope.")
    w("- **A (35)** = Census 2011 districts; Palghar is inside Thane (code 517). **B (36)** = current districts; Palghar (LGD 681) "
      "is rebuilt from its 8 Census 2011 sub-districts in every source (PCA sub-district rows, Village Directory sub-district "
      "codes, Agriculture Census Table 26 tahsils, Survey of India polygon). Rebuilt Palghar population = 2,990,116 and "
      "present-day Thane = 8,070,032, which are the official Census 2011 figures for the two districts.")
    w("- Mumbai City (519) and Mumbai Suburban (518) stay in every table but are flagged `in_index_scope = False` "
      "(config `exclude_mumbai_from_index`, FIXED): the Village Directory has no villages and the Agriculture Census "
      "report no holdings for them, so irrigation, cropped-land and landholding variables do not exist.\n")

    w("## 2. Which source supplies each variable, and which year does it represent?\n")
    src = master_reg.reset_index()[["group", "feature", "role", "source", "year"]]
    w(md_table(src))
    sp = cfg["decisions"]["study_period"]
    w(f"\nSource years: Census 2011 PCA and Village Directory = 2011; Agriculture Census = 2010-11; IMD rainfall = "
      f"{sp['first_year']}-{sp['last_year']} (primary; the 2025 file is kept in data/raw for sensitivity only); NOAA RONI / "
      f"ONI v6 = {sp['first_year']}-{sp['last_year']}; Survey of India boundaries = 2025 vintage; drought GRs = 2018, 2023, "
      "2026 (validation only; 2026 holdout).\n")

    w("## 3. How are geography differences handled?\n")
    w("- Every join is by numeric code: Census 2011 district code = Survey of India `DIST_LGD` (Palghar 681) = ICRISAT "
      "`INDC_DTC` = DataMeet `censuscode`. All 355 Census 2011 talukas match Survey of India `SUBDIS_LGD` codes exactly, "
      "so taluka boundaries are unchanged since 2011 apart from Palghar becoming a district.")
    w("- Sources without codes (Agriculture Census report, GR annexures) use explicit name-to-code tables "
      "(`src/s04_agcensus.py: REPORT_NAME_TO_CODE`, `data/manual/*.csv`). No fuzzy matching is used anywhere.")
    w("- Renamed districts: Aurangabad -> Chhatrapati Sambhajinagar (515), Osmanabad -> Dharashiv (525), "
      "Ahmednagar -> Ahilyanagar (522). Codes are unchanged; all names are kept in `district_crosswalk.csv`.")
    w("- Rainfall is aggregated separately over A and B polygons (active boundary source: Survey of India; A = Thane and "
      "Palghar polygons dissolved).\n")

    w("## 4. Which variables have missing values?\n")
    w(md_table(miss) if len(miss) else "No missing values.\n")
    w("Policy: no imputation or interpolation (config `missing_value_policy`).\n")

    w("## 5. Which variables are derived?\n")
    der = master_reg[master_reg.formula.astype(str).str.len() > 0].reset_index()[["feature", "formula", "unit"]]
    w(md_table(der))

    w("## 6. Which variables are potentially redundant?\n")
    w("Structural (by construction):")
    w("- `irr_rainfed_share_of_cropped_land_pct` = 100 - `irr_irrigated_share_of_cropped_land_pct`")
    w("- `soc_non_worker_share_pct` = 100 - `soc_work_participation_rate_pct`")
    w("- `soc_agri_worker_share_of_workers_pct` = `soc_cultivator_share_of_workers_pct` + `soc_agri_labourer_share_of_workers_pct`")
    w("- two denominators each for marginal-worker share and agricultural-worker share (config choices)")
    w("- `land_marginal_holding_share_pct` is a component of `land_small_holding_share_pct`\n")
    w(f"Empirical, among PCA candidates within the index scope (n = {len(scope)}), |r| >= 0.9 (reported only; nothing removed):\n")
    w(md_table(red, 3) if len(red) else "none\n")

    w("## 7. What anomalies were found?\n")
    n387 = int(vq.villages_sources_match_col387.sum()); n388 = int(vq.villages_sources_match_col388.sum()); nv = int(vq.n_villages.sum())
    w(f"1. **Village Directory irrigation labels are swapped.** Source-wise irrigated areas sum to the column labelled "
      f"'Total Unirrigated Land Area' in {n387:,} of {nv:,} villages (to the column labelled 'Area Irrigated by Source' in "
      f"only {n388:,}). The code maps raw -> analytical fields explicitly; the raw file is untouched.")
    w(f"2. **Negative values** in the true-unirrigated column: {int(vq.n_negative_unirrigated_area_ha.sum())} villages. Active "
      f"policy `keep_raw`; the clipped alternative changes a district's irrigated share by at most "
      f"{vq.clip_minus_raw_pct_points.abs().max():.2f} percentage points.")
    br = vq[vq.villages_irr_plus_unirr_ne_nas > 0]
    w(f"   Irrigated + unirrigated equals net area sown in every village except {int(vq.villages_irr_plus_unirr_ne_nas.sum())} "
      f"({', '.join(names.get(d, str(d)) for d in br.district_id)}); e.g. one Jalgaon village has net area sown 0 but 3,401 ha "
      "unirrigated, so Jalgaon's irrigated + rainfed shares sum to 100.4%. Kept as published.")
    t5 = aq[aq.flag.notna()]
    w(f"3. **Agriculture Census Table 5 errors:** {', '.join(t5.report_name)}. Chandrapur's 2010-11 row reproduces Gondia's "
      "distribution; Dhule's Small/Large columns disagree with Tables 2 and 26. Features use Table 2, which equals the "
      f"Table 26 tahsil totals in all 33 districts (max |difference| = {aq.diff_total_t2_minus_t26.abs().max():.0f} holdings).")
    w("4. **Survey of India sub-district layer:** Dhule's 4 sub-districts carry `DIST_LGD` 598 instead of 498 (district layer is correct). "
      "Sub-district DISTRICT names are in a legacy font encoding; codes are used instead.")
    rm = chk[~chk.match]
    w(f"5. **ENSO classification check:** pipeline reproduces {int(chk[chk['index']=='ONI_v6'].match.sum())}/"
      f"{int((chk['index']=='ONI_v6').sum())} ONI v6 and {int(chk[chk['index']=='RONI'].match.sum())}/"
      f"{int((chk['index']=='RONI').sum())} RONI cells of NOAA's published episode tables. Mismatches: "
      + "; ".join(f"{r['index']} {r.YR} {r.SEAS} ({r.ANOM})" for _, r in rm.iterrows())
      + " - a 1984 La Nina run whose first value is exactly -0.45 in the 2-decimal file (NOAA likely rounds from more precision); "
      "no El Nino season is affected.")
    low = rq[rq.low_cell_count_flag]
    part = rq[rq.partial_valid_coverage_flag]
    cov_txt = ("every grid cell intersecting every district had valid data on every day, so the valid-cell renormalisation "
               "was never triggered" if part.empty else
               "districts with < 90% of area covered by valid cells on some day: "
               + ", ".join(f"{names.get(d, d)} ({s:.0%})" for d, s in zip(part.district_id, part.min_daily_valid_weight_share)))
    w(f"6. **Rainfall grid:** districts intersecting < 10 grid cells: "
      f"{', '.join(f'{names.get(d, d)} ({n})' for d, n in zip(low.district_id, low.n_grid_cells_intersecting)) or 'none'}; "
      f"{cov_txt}. Valid cells in the Maharashtra box: {gq.n_cells_valid_all_days.min()} in every year "
      f"(grid mask unchanged {gq.year.min()}-{gq.year.max()})." if gq.n_cells_valid_all_days.nunique() == 1 else
      f"6. **Rainfall grid:** valid cells vary by year ({gq.n_cells_valid_all_days.min()}-{gq.n_cells_valid_all_days.max()}); {cov_txt}.")
    w(f"7. **Village Directory vs ICRISAT net area:** VD net area sown / ICRISAT net cropped area (2010-12) median "
      f"{icr.vd_over_icrisat_ratio.median():.2f}, range {icr.vd_over_icrisat_ratio.min():.2f}-{icr.vd_over_icrisat_ratio.max():.2f} "
      f"(max: {names.get(int(icr.loc[icr.vd_over_icrisat_ratio.idxmax(), 'district_id']), '')}). Different reference years/definitions; "
      "VD is used because it is the Census 2011 source.")
    issues = cq[cq.issue.fillna("").astype(str) != ""]
    w("8. **2023 revenue-circle GR (1021 circles):** " + "; ".join(issues.issue) + ". Taluka spelling variants also occur, so "
      "only circle COUNTS are used; a taluka-level share is not constructed.")
    w("9. **Prototype definitions:** the prototype's `Marginal_Worker_Share_pct` divided by total population; both "
      "denominators are now produced. The prototype rainfall CSV is not used (provenance unverified).")
    w("10. **IMD 2025:** the IMD download page still states 1901-2024; the 2025 file is complete (365 days) but its "
      "final/provisional status is not documented. It is therefore excluded from the primary study period (1950-2024) "
      "and kept in data/raw for a sensitivity check only.")
    exall = pd.read_csv(INTERIM / "rainfall_extreme_district_years.csv")
    ex = exall[exall.flag_type.str.startswith("high")]
    lo = exall[exall.flag_type.str.startswith("low")]
    rc = cfg["decisions"]["rainfall_extreme_values"]
    w(f"11. **Implausibly high district-years in the official IMD grid** (monsoon > "
      f"{rc['flag_ratio']}x baseline; flagged, NOT altered; NOT VERIFIED as errors - "
      "no published correction found): " + "; ".join(f"{names.get(d, d)} {y} ({r:.1f}x)" for d, y, r in
                                                        zip(ex.district_id, ex.year, ex.ratio_to_baseline)) + ". "
      "None of these years is an El Nino monsoon year under either index, so they enter the El Nino-year features only through "
      "the baseline. Largest baseline change if they were excluded: "
      f"{rq.baseline_change_if_flagged_excluded_pct.abs().max():.1f}% "
      f"({names.get(int(rq.loc[rq.baseline_change_if_flagged_excluded_pct.abs().idxmax(), 'district_id']), '')}). "
      "Config `rainfall_extreme_values`: primary = keep all published values; the excluded-baseline version is sensitivity only.")
    ann = pd.read_csv(INTERIM / "district_annual_monsoon_rainfall.csv").merge(
        pd.read_csv(INTERIM / "enso_yearly_features.csv")[["year", "episode_flag"]], on="year")
    sens = []
    for d, g in ann.groupby("district_id"):
        if g.baseline_monsoon_mm.iloc[0] == g.baseline_monsoon_excl_flagged_mm.iloc[0]:
            continue
        alt = (g.monsoon_rainfall_mm - g.baseline_monsoon_excl_flagged_mm) / g.baseline_monsoon_excl_flagged_mm * 100
        en = g.episode_flag
        sens.append({"district": names.get(d, d), "baseline_keep_mm": g.baseline_monsoon_mm.iloc[0],
                     "baseline_excl_flagged_mm": g.baseline_monsoon_excl_flagged_mm.iloc[0],
                     "en_mean_deficit_keep_pct": -g.monsoon_departure_pct[en].mean(), "en_mean_deficit_excl_pct": -alt[en].mean(),
                     "en_deficient_freq_keep": g.deficient_monsoon[en].mean(), "en_deficient_freq_excl": (alt[en] <= -20).mean(),
                     "nonen_deficient_freq_keep": g.deficient_monsoon[~en].mean()})
    med = ann[~ann.episode_flag].groupby("district_id").deficient_monsoon.mean().median()
    w(f"   Sensitivity of El Nino features to excluding the high-flagged years from the baseline (state median non-El-Nino "
      f"deficient frequency = {med:.2f}):\n")
    w(md_table(pd.DataFrame(sens)))
    w("   Pune's hazard features are the most affected and should be treated as unreliable until the IMD values are checked.\n")
    w(f"12. **Very low district-years (< {rc['low_flag_ratio']}x baseline; review only, never excluded):** "
      + "; ".join(f"{names.get(d, d)} {y} ({r:.2f}x)" for d, y, r in zip(lo.district_id, lo.year, lo.ratio_to_baseline))
      + ". The 1972 entries coincide with Maharashtra's historic 1972 drought; the others ("
      + ", ".join(f"{names.get(d, d)} {y}" for d, y in zip(lo.district_id, lo.year) if y != 1972)
      + ") are unexplained and should be checked against another source before individual years are interpreted.\n")

    w("## 8. Which decisions remain unresolved?\n")
    if unresolved:
        w(md_table(pd.DataFrame(unresolved, columns=["decision", "active default", "options"])))
    else:
        w("None: all decisions in `config/project_decisions.yaml` are FIXED for the primary analysis "
          f"(geography {geo}, ENSO index {idx}). Alternatives are still built in `data/interim/variants/` for sensitivity checks.\n")
    w("\nENSO monsoon-year lists (study period), showing why the index choice matters:\n")
    for col, lab in [("ONI_v6_episode", "ONI v6, all_JJA_JAS"), ("RONI_episode", "RONI, all_JJA_JAS"),
                     ("elnino_monsoon_any_JJA_JAS_ONI_v6", "ONI v6, any_JJA_JAS"), ("elnino_monsoon_any_JJA_JAS_RONI", "RONI, any_JJA_JAS")]:
        yrs = enso_cmp[enso_cmp[col]].year.tolist()
        w(f"- {lab} ({len(yrs)}): {', '.join(map(str, yrs))}")
    w("\nAgreement of climate features between RONI and ONI v6 (geography A, correlation across districts):\n")
    w(md_table(vc, 3))

    w("## 9. Which variables are suitable for PCA, and which are context/validation only?\n")
    w(f"- **PCA candidates ({len(cand)})** - not yet selected; redundancy in section 6 must be resolved first: " + ", ".join(f"`{c}`" for c in cand))
    w(f"- **Context only ({len(ctx)})**: " + ", ".join(f"`{c}`" for c in ctx))
    w(f"- **Identifiers ({len(ids)})**: " + ", ".join(f"`{c}`" for c in ids))
    w("- **Validation only** (never in the index): `drought_validation.csv` - declared-taluka shares 2018, 2023 and "
      "2026 (2026 strictly holdout), plus additional revenue-circle counts 2018/2023.\n")
    w(f"Validation totals reproduce the GRs: 2018 = {int(val.declared_talukas_2018.sum())} talukas, 2023 = "
      f"{int(val.declared_talukas_2023.sum())}, 2026 = {int(val.declared_talukas_2026.sum())}; revenue circles 2018 = "
      f"{int(val.addl_revenue_circles_2018.sum())}, 2023 = {int(val.addl_revenue_circles_2023.sum())}.\n")

    w("## 10. Rainfall QA summary (active geography)\n")
    w(md_table(rq[["district_id", "n_grid_cells_intersecting", "weights_over_area_ratio", "min_daily_valid_weight_share",
                   "years_available", "missing_monsoon_years", "min_monsoon_mm", "max_monsoon_mm", "baseline_monsoon_mm"]]
               .assign(district=lambda d: d.district_id.map(names))))

    REPORTS.mkdir(exist_ok=True)
    (REPORTS / "data_quality_report.md").write_text("\n".join(L), encoding="utf-8")
